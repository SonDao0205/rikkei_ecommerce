export const shopDashboardApi = {
  getDashboardData: async (filter?: ShopDateFilter): Promise<ShopDashboardData> => {
    // Simulated network delay
    await new Promise((resolve) => setTimeout(resolve, 150));
    if (filter) {
      return { ...initialShopDashboardData };
    }
    return initialShopDashboardData;
  },

  confirmOrder: async (orderId: string): Promise<{ success: boolean; orderId: string }> => {
    await new Promise((resolve) => setTimeout(resolve, 200));
    return { success: true, orderId };
  },

  printShippingLabel: async (orderId: string): Promise<{ success: boolean; labelUrl: string }> => {
    await new Promise((resolve) => setTimeout(resolve, 200));
    return { success: true, labelUrl: `#shipping-label-${orderId}` };
  },
};
